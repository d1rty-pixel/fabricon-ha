"""The Fabricon dashboard and its card, provided by the integration itself.

- The card (frontend/fabricon-card.js, bundled from the repository's card/*.js) is served under /fabricon_static/ and
  loaded on every frontend page (add_extra_js_url), so no Lovelace resource is needed.
- The dashboard (/fabricon-dashboard) is generated by dashboard/ from the device registry: one view per BamBuddy
  printer, plus the demo printers when that option is on. It lives in memory (a read-only Lovelace config like a
  YAML dashboard) and is rebuilt at every start, when a printer is added and on the fabricon.rebuild service.

Home Assistant has no public API for an integration to add a dashboard: this uses the lovelace component's
dashboard table and LovelaceConfig base class, the same way lovelace registers its own YAML dashboards.
"""
import hashlib
import importlib
import json
import logging
import sys
from pathlib import Path

from homeassistant.components import frontend
from homeassistant.components.http import StaticPathConfig
from homeassistant.components.lovelace.const import EVENT_LOVELACE_UPDATED, LOVELACE_DATA
from homeassistant.components.lovelace.dashboard import LovelaceConfig
from homeassistant.helpers import device_registry as dr
from homeassistant.helpers import entity_registry as er
from homeassistant.helpers.json import json_bytes, json_fragment
from homeassistant.helpers.storage import Store

from .const import DOMAIN

_LOG = logging.getLogger(__name__)
HERE = Path(__file__).parent
STATIC = "/fabricon_static"
CARD = HERE / "frontend" / "fabricon-card.js"
# the generator's modules in dependency order (each imports only ones before it); reloaded by fabricon.rebuild
MODULES = ["settings", "lib", "spec", "providers.bambuddy", "providers", "templates", "controls", "panels", "view", "demo", "build"]
DEMO_TAGS = (".x2d_demo_", ".fab_demo_")   # entity prefixes of the demo printers (dashboard/demo.py)


def _generator(reload=False):
    """dashboard.build and dashboard.demo, imported (or reloaded after an update on disk) in this order. Blocking."""
    pkg = f"{__package__}.dashboard"
    mods = {}
    for name in MODULES:
        full = f"{pkg}.{name}"
        mods[name] = importlib.reload(sys.modules[full]) if reload and full in sys.modules else importlib.import_module(full)
    return mods


class FabriconDashboard(LovelaceConfig):
    """A Lovelace config held in memory; the frontend shows it like a YAML dashboard (not editable)."""

    def __init__(self, hass, url_path, info):
        super().__init__(hass, url_path, info)
        self.data = {"title": info["title"], "views": []}
        self._json = json_fragment(json_bytes(self.data))

    @property
    def mode(self):
        return "yaml"

    async def async_get_info(self):
        return {"mode": self.mode, "views": len(self.data.get("views", []))}

    async def async_load(self, force):
        return self.data

    async def async_json(self, force):
        return self._json

    def set(self, data):
        self.data = data
        self._json = json_fragment(json_bytes(data))
        self.hass.bus.async_fire(EVENT_LOVELACE_UPDATED, {"url_path": self.url_path})


async def async_setup_card(hass):
    """Serve the card and load it on every page; the URL carries the file's hash, so browsers fetch a new build."""
    data = hass.data[DOMAIN]
    if not data.get("static"):
        await hass.http.async_register_static_paths([StaticPathConfig(STATIC, str(HERE / "frontend"), False)])
        data["static"] = True
    if not await hass.async_add_executor_job(CARD.is_file):
        _LOG.error("%s is missing: the card was not bundled into this copy of the integration", CARD)
        return
    sha = await hass.async_add_executor_job(lambda: hashlib.sha256(CARD.read_bytes()).hexdigest()[:8])
    url = f"{STATIC}/{CARD.name}?v={sha}"
    if data.get("card") != url:
        if data.get("card"):
            frontend.remove_extra_js_url(hass, data["card"])
        frontend.add_extra_js_url(hass, url)
        data["card"] = url


def async_remove_card(hass):
    url = hass.data[DOMAIN].pop("card", None)
    if url:
        frontend.remove_extra_js_url(hass, url)


async def async_register_dashboard(hass):
    """Add the dashboard to Lovelace and the sidebar; False if another dashboard already uses the path."""
    s = (await hass.async_add_executor_job(_generator))["settings"]
    dashboards = hass.data[LOVELACE_DATA].dashboards
    existing = dashboards.get(s.URL_PATH)
    if existing is not None and not isinstance(existing, FabriconDashboard):
        _LOG.error("a dashboard at /%s already exists; delete it (Settings -> Dashboards) and reload Fabricon", s.URL_PATH)
        return False
    if existing is None:
        info = {"mode": "yaml", "title": s.TITLE, "icon": s.ICON, "show_in_sidebar": True, "require_admin": False}
        dashboards[s.URL_PATH] = FabriconDashboard(hass, s.URL_PATH, info)
        frontend.async_register_built_in_panel(
            hass, "lovelace", frontend_url_path=s.URL_PATH, require_admin=False, show_in_sidebar=True,
            sidebar_title=s.TITLE, sidebar_icon=s.ICON, config={"mode": "yaml"}, update=False)
    hass.data[DOMAIN]["dashboard"] = dashboards[s.URL_PATH]
    return True


def async_remove_dashboard(hass):
    board = hass.data[DOMAIN].pop("dashboard", None)
    if board is None:
        return
    frontend.async_remove_panel(hass, board.url_path)
    hass.data[LOVELACE_DATA].dashboards.pop(board.url_path, None)


def _devices(hass):
    """Every device entry: iterating the registry's devices gives entries on current cores, ids on older ones."""
    devices = dr.async_get(hass).devices
    items = list(devices)
    return [devices[i] for i in items] if items and isinstance(items[0], str) else items


def _registry(hass):
    devs = [{"id": d.id, "identifiers": [list(i) for i in d.identifiers], "via_device_id": d.via_device_id,
             "model": d.model, "name": d.name, "name_by_user": d.name_by_user}
            for d in _devices(hass)]
    ents = [{"entity_id": e.entity_id, "device_id": e.device_id} for e in er.async_get(hass).entities.values()]
    return devs, ents


def printer_list(hass):
    """The printers the dashboard shows, with their spec (for the options flow). Blocking (imports the generator)."""
    return _generator()["build"].printers(*_registry(hass))


def printer_ids(hass):
    """Entity prefixes of the printers the dashboard would show (to notice a new one)."""
    return [p["P"] for p in _generator()["build"].printers(*_registry(hass))]


async def async_build(hass, entry, reload=False):
    """Generate the dashboard from the registries and the entry's options, and show it."""
    data = hass.data[DOMAIN]
    board = data.get("dashboard")
    if board is None:
        return
    mods = await hass.async_add_executor_job(_generator, reload)
    devs, ents = _registry(hass)
    ps = mods["build"].printers(devs, ents)
    bambuddy = hass.config_entries.async_entries("bambuddy")
    options = {"ams": entry.options.get("ams", True), "exhaust_box": entry.options.get("exhaust_box", False),
               "demo": entry.options.get("demo", False), "printers": entry.options.get("printers", {}),
               "bambuddy_url": bambuddy[0].data.get("url", "") if bambuddy else ""}
    if options["demo"] and not ps:
        options["demo"] = False   # demos copy a real printer
    await _async_demo(hass, mods["demo"], ps[0]["P"] if options["demo"] else None)
    stl = Path(hass.config.path("www", mods["settings"].STL))
    stl_version = await hass.async_add_executor_job(
        lambda: hashlib.sha256(stl.read_bytes()).hexdigest()[:8] if stl.is_file() else "")
    config = await hass.async_add_executor_job(mods["build"].build, ps, options, stl_version)
    board.set(config)
    data["printers"] = [p["P"] for p in ps]
    data["providers"] = {p["serial"].upper(): p.get("provider", "bambuddy") for p in ps}   # the print proxy's backend
    _LOG.info("dashboard /%s: %d view(s)", board.url_path, len(config["views"]))


async def _async_demo(hass, demo, source):
    """Demo printer states: a snapshot of the source printer's states (taken while it is online, kept in .storage)
    with each demo's profile on top, and the model demos' made-up states. source None: remove them."""
    store = Store(hass, 1, f"{DOMAIN}.demo")
    states = {}
    if source:
        online = hass.states.get(f"binary_sensor.{source}_online")
        if online is not None and online.state == "on":
            snap = [{"entity_id": s.entity_id, "state": s.state, "attributes": dict(s.attributes)}
                    for s in hass.states.async_all() if s.entity_id.split(".", 1)[1].startswith(source + "_")]
            states = demo.demo_states(json.loads(json_bytes(snap)), source)   # plain JSON types for the store
            await store.async_save(states)
        else:
            states = await store.async_load() or {}
    if source:   # the model demos are made up from their profiles, no snapshot needed
        states = {**states, **await hass.async_add_executor_job(demo.model_states)}
    for eid, st in states.items():
        hass.states.async_set(eid, st["state"], st["attributes"])
    for s in hass.states.async_all():
        if any(t in s.entity_id for t in DEMO_TAGS) and s.entity_id not in states:
            hass.states.async_remove(s.entity_id)
